require('dotenv').config();
const express=require('express');
const path=require('path');
const tripController=require('./controllers/tripController');
const app=express();
app.set('view engine','pug');
app.set('views',path.join(__dirname,'views'));
app.use(express.static(path.join(__dirname,'public')));
app.get('/',(req,res)=>res.render('home',{title:'Home'}));
app.get('/trips',tripController.list);
app.get('/trips/:id',tripController.detail);
app.get('/health',(req,res)=>res.json({status:'ok'}));
app.use((err,req,res,next)=>{console.error(err);res.status(500).send('Unable to load data. Check the database connection.');});
const port=Number(process.env.PORT||3000);
app.listen(port,'0.0.0.0',()=>console.log('TravelMate: http://localhost:'+port));
